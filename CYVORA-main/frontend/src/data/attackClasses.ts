export const RARE_ATTACK_CLASSES: AttackClassInfo[] = CYVORA_ATTACK_CLASSES.filter((c) => c.isRare);

export const getAttackInfo = (name: string): AttackClassInfo => {
  const found = CYVORA_ATTACK_CLASSES.find(
    (c) => c.name.toLowerCase() === name.toLowerCase() || name.toLowerCase().includes(c.name.toLowerCase())
  );
  if (found) return found;

  return {
    name,
    category: 'Unknown / Suspicious',
    severity: 'MEDIUM',
    mitreId: 'T1190',
    mitreTactic: 'Defense Evasion',
    description: `Security anomaly detected by CYVORA intelligence engine: ${name}.`,
    frequency: 'Anomaly Signal',
    recommendedAction: 'ALERT security operations team and inspect raw packet telemetry.',
    indicators: ['Anomalous packet flow metric', 'Unusual port/duration combination'],
    typicalPorts: [80, 443],
    isRare: false,
  };
};
